/**
 * Fragment templates for the editor's "fragment" tool.
 * OWNER: forcefield agent. CONTRACT: keep exported names & signatures.
 *
 * Rings: benzene, cyclohexane (chair), cyclopentane, cyclopropane, pyridine, pyrrole, furan, thiophene,
 * naphthalene, imidazole; alkyl chains; functional groups (hydroxyl, amine, carbonyl, carboxyl,
 * aldehyde, ester, nitro, nitrile, amide, phenyl, CF₃, sulfonyl, sulfonamide, phosphate, …);
 * amino acids glycine and L-alanine.
 *
 * Templates include explicit hydrogens. The attach atom is the one that bonds to the anchor;
 * `attachHydrogen` is the index of the H on attachAtom that is removed when attaching (so the
 * fragment's valence stays correct). Its position gives the attachment direction: the anchor goes
 * where that H is.
 *
 * Coordinates (Å) were generated with this project's own SMILES embedder + force field
 * (core/smiles.ts, core/minimize.ts; bond lengths from idealBondLength with conjugation corrections)
 * and are stored statically. Frame: attach atom at the origin, attachHydrogen on the +x axis, the
 * rest of the fragment towards −x. Every template is valence-consistent (see templates.test.ts).
 */
import type { BondOrder } from './types';

export interface FragmentTemplate {
  id: string;
  name: string;
  category: 'ring' | 'group' | 'chain' | 'biomolecule';
  description?: string;
  /** Short label for the toolbar button, e.g. 'Ph', 'OH', 'COOH'. */
  label: string;
  atoms: { element: string; x: number; y: number; z: number; charge?: number }[];
  /** Bonds referencing atom indices. */
  bonds: { a: number; b: number; order: BondOrder }[];
  /** Index of the atom that bonds to the anchor. */
  attachAtom: number;
  /** Index of the hydrogen on attachAtom that is replaced when attaching (pointing to where the anchor goes). */
  attachHydrogen: number;
  /** SMILES of the template molecule (attach atom first), for reference / display. */
  smiles?: string;
}

